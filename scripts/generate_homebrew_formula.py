"""Generate a tap formula for a built sdist; emit nothing on invalid inputs.

The first distribution uses one resource set for macOS/Linux and Python 3.12.
Platform-specific graphs and ambiguous lock entries require a maintainer update.
"""

import argparse
import hashlib
import re
import tomllib
from pathlib import Path

from packaging.markers import Marker

HOMEPAGE = "https://github.com/ogbozoyan/PermaEnv"


def applies(marker: str) -> bool:
    """Only accept markers whose meaning is stable across the supported tap targets."""
    # Do not accidentally evaluate host-specific marker fields on the build runner.
    allowed = {"sys_platform", "os_name", "platform_system", "python_version"}
    fields = re.findall(r"\b[a-z][a-z_]+\b", re.sub(r"'[^']*'|\"[^\"]*\"", "", marker))
    if set(fields) - allowed - {"and", "or", "in", "not"}:
        raise ValueError(f"Unsupported Homebrew dependency marker: {marker}")
    results = {
        Marker(marker).evaluate(
            environment={
                "sys_platform": os_name,
                "os_name": "posix",
                "platform_system": system,
                "python_version": "3.12",
            }
        )
        for os_name, system in [("darwin", "Darwin"), ("linux", "Linux")]
    }
    if len(results) != 1:
        raise ValueError(f"Platform-specific Homebrew dependency: {marker}")
    return results.pop()


def generate(sdist: Path, lock_path: Path) -> str:
    lock = tomllib.loads(lock_path.read_text())
    packages = lock["package"]

    def package(name: str) -> dict:
        matches = [item for item in packages if item["name"] == name]
        if len(matches) != 1:
            raise ValueError(f"Expected exactly one locked package: {name}")
        return matches[0]

    root = package("permaenv")
    version = root["version"]
    if not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+(?:[a-z]+[0-9]+|\.dev[0-9]+)?", version):
        raise ValueError("Unsupported release version")
    if sdist.name != f"permaenv-{version}.tar.gz":
        raise ValueError("Source archive filename must match the locked PermaEnv version")
    with sdist.open("rb") as archive:
        checksum = hashlib.file_digest(archive, "sha256").hexdigest()
    pending = list(root.get("dependencies", []))
    resources = {}
    while pending:
        dep = pending.pop()
        if "marker" in dep and not applies(dep["marker"]):
            continue
        if set(dep) - {"name", "marker"}:
            raise ValueError(f"Unsupported dependency selector: {dep}")
        name = dep["name"]
        if name in resources:
            continue
        item = package(name)
        source = item.get("sdist", {})
        url, digest = source.get("url", ""), source.get("hash", "")
        if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", name):
            raise ValueError("Invalid resource name")
        if not re.fullmatch(r"https://files\.pythonhosted\.org/[a-zA-Z0-9/_.%-]+", url):
            raise ValueError(f"Expected a public PyPI source archive: {name}")
        if not re.fullmatch(r"sha256:[0-9a-f]{64}", digest):
            raise ValueError(f"Missing SHA-256 source checksum: {name}")
        resources[name] = (url, digest.removeprefix("sha256:"))
        pending.extend(item.get("dependencies", []))

    lines = [
        "# Generated by scripts/generate_homebrew_formula.py; do not edit by hand.",
        "class Permaenv < Formula",
        "  include Language::Python::Virtualenv",
        "",
        '  desc "Portable developer environment toolkit"',
        f'  homepage "{HOMEPAGE}"',
        f'  url "{HOMEPAGE}/releases/download/v{version}/{sdist.name}"',
        f'  version "{version}"',
        f'  sha256 "{checksum}"',
        '  license "MIT"',
        "",
        '  depends_on "python@3.12"',
    ]
    for name, (url, digest) in sorted(resources.items()):
        lines.extend(
            [
                "",
                f'  resource "{name}" do',
                f'    url "{url}"',
                f'    sha256 "{digest}"',
                "  end",
            ]
        )
    lines.extend(
        [
            "",
            "  def install",
            "    virtualenv_install_with_resources",
            "  end",
            "",
            "  test do",
            '    report = JSON.parse(shell_output("#{bin}/permaenv doctor --json"))',
            '    assert_equal 1, report.fetch("schema_version")',
            '    assert_equal true, report.fetch("platform").fetch("supported")',
            '    assert report.fetch("tools").any? { |tool| tool.fetch("name") == "brew" }',
            "  end",
            "end",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sdist", type=Path, required=True)
    parser.add_argument("--lock", type=Path, default=Path("uv.lock"))
    args = parser.parse_args()
    try:
        formula = generate(args.sdist, args.lock)
    except (ValueError, KeyError, OSError) as error:
        parser.error(str(error))
    print(formula, end="")


if __name__ == "__main__":
    main()
